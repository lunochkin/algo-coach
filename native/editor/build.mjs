// bundles `page.ts` into the HTML string the app ships, with a hash of every
// source the bundle was built from. `src/editor/page.test.ts` compares it
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export function sourceHash() {
  const shared = join(here, '../../packages/editor/src');
  const files = [
    join(here, 'page.ts'),
    join(here, 'protocol.ts'),
    ...readdirSync(shared)
      .filter((name) => name.endsWith('.ts') && !name.endsWith('.test.ts'))
      .sort()
      .map((name) => join(shared, name)),
  ];
  const hash = createHash('sha256');
  for (const file of files) hash.update(readFileSync(file));
  return hash.digest('hex').slice(0, 16);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { build } = await import('rolldown');
  const out = await build({
    input: join(here, 'page.ts'),
    write: false,
    output: { format: 'iife', minify: true },
  });
  const js = out.output[0].code.replaceAll('</script>', '<\\/script>');
  const html =
    '<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1">' +
    `</head><body><div id="editor"></div><script>${js}</script></body></html>`;
  writeFileSync(
    join(here, '../src/editor/page.ts'),
    `// generated by \`just editor-page\` from native/editor: do not edit\n` +
      `export const SOURCE_HASH = '${sourceHash()}';\n` +
      `export const PAGE = ${JSON.stringify(html)};\n`,
  );
}
